import type { Investigation } from "./types";
import { fmtEffect, fmtP, slug } from "./utils";

export function dossierToMarkdown(inv: Investigation): string {
  const L: string[] = [];
  const S = (s: string) => L.push(s);

  S(`# BioSynthetica Research Dossier`);
  S("");
  S(`**Research question:** ${inv.question}`);
  S(`**Mode:** ${inv.mode}  |  **Generated:** ${new Date(inv.created_at).toISOString()}  |  **Engine:** ${inv.demo ? "demo replay" : "live engine"}`);
  S("");
  S(`## Evidence summary`);
  const s = inv.summary;
  S(`- Papers analyzed: ${s.papers_analyzed}`);
  S(`- Claims extracted: ${s.claims} (evidence anchors: ${s.evidence_anchors})`);
  S(`- Conflict groups: ${s.conflict_groups} (pairs: ${s.conflicting_pairs})`);
  S(`- Mechanism chains: ${inv.mechanisms.length}`);
  S(`- Hypotheses: ${s.hypotheses}; research gaps: ${s.research_gaps}`);
  S(`- GEO closures: ${s.geo_closures}; audit flags: ${s.audit_flags}`);
  S("");
  S(`## Sources`);
  for (const p of inv.papers) {
    S(`- [${p.id}] ${p.title} — ${p.authors.join(", ")} (${p.journal}, ${p.year}). DOI: ${p.doi}; PMID: ${p.pmid}; source: ${p.source_db}; relevance: ${p.relevance.toFixed(2)}`);
  }
  S("");
  S(`## Claims`);
  for (const c of inv.claims) {
    S(`### ${c.id} — ${c.subject}`);
    S(`> ${c.quote}`);
    S("");
    S(`- Statement: ${c.statement}`);
    S(`- Organism: ${c.organism}; Intervention: ${c.intervention}; Dose: ${c.dose}`);
    S(`- Measurement: ${c.measurement}; Direction: ${c.effect_direction}; Effect size: ${fmtEffect(c.effect_size)}; ${fmtP(c.p_value)}; n = ${c.sample_size ?? "—"}`);
    S(`- Method: ${c.statistical_method ?? "—"}; Confidence: ${c.confidence}`);
    S("");
  }
  S(`## Contradictions & conflicts`);
  for (const x of inv.conflicts) {
    S(`### ${x.id} (${x.verdict}) — ${x.claim_a} vs ${x.claim_b}`);
    S(x.reasoning);
    if (x.differences.length) {
      S("");
      S(`| factor | A | B |`);
      S(`|---|---|---|`);
      for (const d of x.differences) S(`| ${d.factor} | ${d.a} | ${d.b} |`);
    }
    S("");
  }
  S(`## Mechanistic pathways`);
  for (const m of inv.mechanisms) {
    S(`- **${m.title}** (${m.hops} hops)`);
    S(`  - ${m.pathway.map((p, i) => (i === 0 ? p : `→ ${p}`)).join(" ")}`);
    S(`  - evidence: ${m.evidence.join(", ")}`);
  }
  S("");
  S(`## Hypotheses`);
  for (const h of inv.hypotheses) {
    S(`### ${h.id} [${h.status}] — ${h.statement}`);
    S(`- Mechanism: ${h.mechanism}`);
    S(`- Predictions: ${h.predictions.map((p) => `"${p}"`).join("; ")}`);
    S(`- Required measurement: ${h.required_measurement}`);
    S(`- Expected result: ${h.expected_result}`);
    S(`- Falsification conditions:`);
    for (const f of h.falsification_conditions) S(`  - ${f}`);
    S(`- Next experiment: ${h.next_experiment}`);
    S("");
  }
  S(`## Research gaps`);
  for (const g of inv.gaps) S(`- [${g.category}] ${g.description}`);
  S("");
  S(`## GEO loop closures`);
  for (const g of inv.geo_closures) {
    S(`- **${g.gse_accession}** — ${g.title} (${g.organism}, n=${g.n_samples})`);
    S(`  - ${g.resolution}`);
    S(`  - links: ${g.links_claims.join(", ")}`);
  }
  S("");
  S(`## Adversarial audit flags`);
  for (const a of inv.audit_flags) S(`- [${a.severity.toUpperCase()}] ${a.target}: ${a.message}`);
  S("");
  S(`---`);
  S(`*Dossier generated by BioSynthetica. Claims are quote-anchored; audit flags note deterministic polarity/consistency checks.*`);
  void slug;
  return L.join("\n");
}
